package tech.nmfin.algoquant.demo;

import dev.nm.nmutils.NMUtils;
import java.awt.Frame;
import java.lang.reflect.Method;
import java.util.*;
import org.reflections.Reflections;
import org.slf4j.Logger;
import tech.nmfin.algoquant.util.annotation.Demo;

/**
 * Runs all demo programs.
 * 
 * This is used to check whether or not any of the demo programs fails to run.
 */
public class RunAllDemo {

    private static final Logger LOGGER = NMUtils.getClassLogger();

    public static void main(String[] args) throws Exception {
        String packageName = RunAllDemo.class.getPackage().getName();
        LOGGER.info(
            "Searching all demo classes in the package {}", 
            packageName
        );

        Reflections reflections = new Reflections(packageName);

        SortedSet<Class<?>> demoClasses
            = new TreeSet<>((o1, o2) -> {
                return o1.getName().compareTo(o2.getName());
            });
        demoClasses.addAll(reflections.getTypesAnnotatedWith(Demo.class));

        LOGGER.info("Demo classes: {}", formatClasses(demoClasses));

        List<Class<?>> failedDemo = new ArrayList<>();

        for (final Class<?> clazz : demoClasses) {
            String className = clazz.getCanonicalName();
            long startTime = System.currentTimeMillis();
            LOGGER.info("Running demo {}...", className);

            try {
                Method main = clazz.getMethod("main", String[].class);
                main.invoke(null, (Object) null);

                // silently kill the Swing GUI generated by the demo program
                for (Frame frame : Frame.getFrames()) {
                    frame.dispose();
                }
            } catch (Throwable th) {
                LOGGER.error(className + " failed", th);
                failedDemo.add(clazz);
            }

            long endTime = System.currentTimeMillis();
            LOGGER.info(
                "Finished demo {} (elapsed time = {}ms)",
                className, (endTime - startTime)
            );
        }

        LOGGER.info(
            "{} demo run: {} failed", 
            demoClasses.size(), failedDemo.size()
        );
        LOGGER.info("failed demos: {}", formatClasses(failedDemo));
    }

    private static String formatClasses(Collection<Class<?>> classes) {
        final String LF = System.lineSeparator();
        StringBuilder sb = new StringBuilder(LF);

        classes.forEach(clazz
            -> sb.append(clazz.getCanonicalName()).append(LF)
        );

        return sb.toString();
    }
}
